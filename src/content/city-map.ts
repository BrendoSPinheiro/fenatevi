/**
 * A geometria dos mapas de Vitória, projetada e simplificada em build.
 *
 * **De onde vem.** Linha de costa e malha viária são dados do OpenStreetMap,
 * obtidos pela Overpass API para os dois recortes abaixo e reduzidos com
 * Douglas–Peucker. Estão congelados aqui, e não buscados em runtime, por três
 * motivos: o portal não faz requisição a terceiros, o mapa precisa existir sem
 * JavaScript, e a cidade não muda de forma entre um deploy e outro.
 *
 * **Atribuição obrigatória.** Os dados são © colaboradores do OpenStreetMap,
 * sob ODbL. A tela que usa este módulo precisa creditá-los de forma visível —
 * é o que `espacos.mapAttribution` faz.
 *
 * **Por que dois recortes.** Cinco dos sete espaços ficam a menos de 500 m uns
 * dos outros, no Centro; os outros dois ficam a cinco quilômetros dali, em
 * Goiabeiras e Jardim da Penha. Num único enquadramento, ou os dois do norte
 * saem do quadro, ou os cinco do Centro viram um borrão de marcadores
 * sobrepostos. A solução é a de qualquer mapa impresso: um mapa geral e um
 * detalhe ampliado, com o recorte do detalhe assinalado no geral.
 *
 * **Projeção.** Web Mercator, com x e y na mesma unidade angular, recortada
 * pelo quadro de cada camada. `projectToLayer` converte latitude e longitude
 * reais em coordenadas do `viewBox`, de modo que o marcador de um espaço venha
 * do endereço dele e não de um valor desenhado à mão.
 */

/** O quadro geográfico de uma camada, em graus decimais. */
export interface MapFrame {
  readonly south: number;
  readonly north: number;
  readonly west: number;
  readonly east: number;
}

/** Um mapa: o seu quadro, as suas dimensões e os seus traços. */
export interface CityMapLayer {
  readonly frame: MapFrame;
  readonly viewBox: { readonly width: number; readonly height: number };
  /** Quantos pixels do `viewBox` equivalem a um quilômetro — a base da escala. */
  readonly pixelsPerKm: number;
  readonly coastline: readonly string[];
  readonly arterialRoads: readonly string[];
  readonly streets: readonly string[];
}

function mercator(longitude: number, latitude: number): { x: number; y: number } {
  return {
    x: (longitude * Math.PI) / 180,
    y: Math.log(Math.tan(Math.PI / 4 + (latitude * Math.PI) / 180 / 2)),
  };
}

/** Converte um ponto geográfico em coordenadas do `viewBox` da camada. */
export function projectToLayer(
  layer: CityMapLayer,
  latitude: number,
  longitude: number,
): { x: number; y: number } {
  const origin = mercator(layer.frame.west, layer.frame.south);
  const corner = mercator(layer.frame.east, layer.frame.north);
  const scale = layer.viewBox.width / (corner.x - origin.x);
  const point = mercator(longitude, latitude);

  return { x: (point.x - origin.x) * scale, y: (corner.y - point.y) * scale };
}

/** O ponto está dentro do quadro desta camada? */
export function isInsideLayer(layer: CityMapLayer, latitude: number, longitude: number): boolean {
  return (
    latitude >= layer.frame.south &&
    latitude <= layer.frame.north &&
    longitude >= layer.frame.west &&
    longitude <= layer.frame.east
  );
}

